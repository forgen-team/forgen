const KIND_ORDER = { rule: 0, solution: 1, habit: 2 } as const;

const rankOf = (i: WayItem) => ({ strength: i.strength, source: i.source ?? 'behavior_inference', updated_at: i.updated_at ?? '', id: i.id });

/** 예산이 모자랄 때 먼저 지키는 순서. 룰끼리는 렌더러(byPriority)와 같은 비교를 쓴다: 강도 → 출처 → 최신. 다른 종류는 강도 다음에 룰 > 솔루션 > 습관. */
export function comparePriority(a: WayItem, b: WayItem): number {
  return (STRENGTH_RANK[a.strength] - STRENGTH_RANK[b.strength]) || (KIND_ORDER[a.kind] - KIND_ORDER[b.kind]) || compareRank(rankOf(a), rankOf(b));
}

