function pickLang(items: WayItem[]): Strings {
  const text = items.map((i) => i.statement).join('');
  const han = (text.match(/[ㄱ-힝]/g) ?? []).length;
  return han > text.length * 0.1 ? KO : EN;
}

const oneLine = (s: string) => s.replace(/\s+/g, ' ').trim();

function firstSentence(s: string, max = 200): string {
  const t = oneLine(s);
  const m = /^.{12,}?[.!?。](?=\s|$)/.exec(t);
  const cand = m ? m[0] : t;
  if (cand.length <= max) return cand;
  const cut = cand.slice(0, max);
  return `${cut.slice(0, Math.max(cut.lastIndexOf(' '), max - 40))}…`;
}

function tag(i: WayItem, L: Strings): string {
  const p = i.provenance;
  if (p.kind === 'you-said' && p.quote) return ` — ${L.said}${p.date ? ` ${p.date}` : ''}: "${p.quote}"`;
  if (p.kind === 'mined') return ` [${L.mined}]`;
  if (p.kind === 'imported') return ` [${L.imported}]`;
  return '';
}

