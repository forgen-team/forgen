const MARK = '<!-- forgen-way: generated by `forgen way export`. Edits are overwritten; change the source rules instead. -->';
const SKILL_MARK = '<!-- forgen-way -->';

/** forgen way 가 쓴 파일인가. 이 표식이 없는 파일은 덮어쓰지 않는다. */
export function isWayManaged(content: string): boolean {
  const head = content.split('\n', 16);
  if (head.some((l) => /^<!-- forgen-way(: [^<>]*)? -->$/.test(l.trim()))) return true;
  // json 산출물은 주석을 쓸 수 없으니 최상위 필드로 본다.
  if (head[0]?.trim() === '{') {
    try { const j = JSON.parse(content) as { schema?: unknown; generator?: unknown }; return j.schema === 'forgen-way/1' && j.generator === 'forgen-way'; } catch { return false; }
  }
  return false;
}

