function asciiSlug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

const CHO = ['g', 'kk', 'n', 'd', 'tt', 'r', 'm', 'b', 'pp', 's', 'ss', '', 'j', 'jj', 'ch', 'k', 't', 'p', 'h'];
const JUNG = ['a', 'ae', 'ya', 'yae', 'eo', 'e', 'yeo', 'ye', 'o', 'wa', 'wae', 'oe', 'yo', 'u', 'wo', 'we', 'wi', 'yu', 'eu', 'ui', 'i'];
const JONG = ['', 'k', 'kk', 'ks', 'n', 'nj', 'nh', 't', 'l', 'lk', 'lm', 'lb', 'ls', 'lt', 'lp', 'lh', 'm', 'p', 'ps', 't', 'tt', 'ng', 't', 't', 'k', 't', 'p', 'h'];

/** 국어의 로마자 표기(음운 변동 없이 글자 단위)로 슬러그용 ASCII 를 만든다. 의미는 못 살려도 사람이 구분할 수 있는 이름이 된다. */
export function romanize(s: string): string {
  let out = '';
  for (const ch of s) {
    const c = ch.codePointAt(0) ?? 0;
    if (c >= 0xac00 && c <= 0xd7a3) {
      const n = c - 0xac00;
      out += `${CHO[Math.floor(n / 588)]}${JUNG[Math.floor((n % 588) / 28)]}${JONG[n % 28]}`;
    } else out += /[A-Za-z0-9]/.test(ch) ? ch : ' ';
  }
  return out;
}

const shortId = (id: string) => createHash('sha256').update(id).digest('hex').slice(0, 4);

/** 슬러그 길이 제한을 단어 경계에서 지킨다. */
function clipSlug(slug: string, max: number): string {
  if (slug.length <= max) return slug;
  const cut = slug.slice(0, max);
  const k = cut.lastIndexOf('-');
  return (k >= 8 ? cut.slice(0, k) : cut).replace(/-+$/g, '');
}

function skillName(i: WayItem, used: Set<string>): string {
  const src = i.kind === 'solution' ? i.id.replace(/^solution:/, '') : i.statement.slice(0, 80);
  let base = asciiSlug(src);
  if (base.length < 3) base = asciiSlug(romanize(src));
  if (base.length < 3) base = `${asciiSlug(i.category ?? i.kind) || i.kind}-${shortId(i.id)}`;
  base = clipSlug(base, 48);
  let name = base;
  if (used.has(name)) name = `${clipSlug(base, 43)}-${shortId(i.id)}`;
  for (let n = 2; used.has(name); n++) name = `${clipSlug(base, 40)}-${shortId(i.id)}${n}`;
  used.add(name);
  return name;
}

/** 스킬로 낼 만한가: 솔루션이고 실제 상황 문장(공백이 있는 Context)이 있어야 한다. 룰의 trigger 는 사용 시점이 아니다. */
export function isSkillable(i: WayItem): boolean {
  return i.kind === 'solution' && /\s/.test(i.applies_when.trim());
}

function yamlStr(s: string): string {
  return JSON.stringify(s); // JSON 문자열은 유효한 YAML 큰따옴표 스칼라다.
}

const hasUseTime = (i: WayItem) => i.kind === 'solution' && /\s/.test(oneLine(i.applies_when));

function skillFile(i: WayItem, name: string, L: Strings, degradedNote: string[]): CompiledFile {
  let desc = hasUseTime(i) ? `${L.skillUse}: ${oneLine(i.applies_when)}. ${firstSentence(i.statement)}` : firstSentence(i.statement, 300);
  if (!hasUseTime(i)) degradedNote.push(`${i.id}: 낮은 품질: 사용 시점이 없어 description 이 호출 조건이 아니다. forgen way draft skill "<주제>" 로 초안을 쓰라`);
  if (desc.length > 1024) { desc = `${desc.slice(0, 1023)}…`; degradedNote.push(`${i.id}: description 1024자 제한으로 줄임`); }
  const p = i.provenance;
  const why = i.why || (p.kind === 'you-said' ? `${L.said}${p.date ? ` ${p.date}` : ''}` : p.kind === 'imported' ? `${L.imported}: ${p.from}` : p.kind === 'mined' ? `${L.mined}` : '') || L.unknownWhy;
  const care = [
    `${L.strength}: ${i.strength}`,
    `${L.scope}: ${i.projects.length ? i.projects.join(', ') : L.global}`,
    i.enforceable ? L.enforcedNote : L.advisory,
  ];
  const title = i.kind === 'solution' ? name : firstSentence(i.statement, 70);
  const prohibition = i.kind === 'rule' && NEGATION_RE.test(i.statement);
  const bodyHead = i.kind === 'solution'
    ? [`## ${L.skillWhen}`, i.applies_when || L.global, '', `## ${L.skillDo}`, i.statement.trim()]
    : [`## ${prohibition ? L.skillBan : L.skillRule}`, i.statement.trim(), ...(readableWhen(i) ? ['', `## ${L.skillSituation}`, readableWhen(i)] : [])];
  const body = [
    '---', `name: ${name}`, `description: ${yamlStr(desc)}`, 'metadata:', `  forgen-way-id: ${yamlStr(i.id)}`, `  generated-by: "forgen-way"`, '---',
    SKILL_MARK, '', `# ${title}`, '', ...bodyHead, '', `## ${L.skillWhy}`, why, '', `## ${L.skillCare}`, ...care.map((c) => `- ${c}`), '',
  ].join('\n');
  return { path: `.claude/skills/${name}/SKILL.md`, content: body };
}

// ── 대상별 렌더 ──

function renderFiles(target: CompileTarget, items: WayItem[], L: Strings, o: CompileOptions, notes: string[], genAt = ''): CompiledFile[] {
  switch (target) {
    case 'agents-md': return [{ path: 'AGENTS.md', content: `${MARK}\n${markdownBody(items, L, target, o.project)}` }];
    case 'claude-rules': return [{ path: '.claude/rules/forgen-way.md', content: `${MARK}\n${markdownBody(items, L, target, o.project)}` }];
    case 'gemini': return [{ path: 'GEMINI.md', content: `${MARK}\n${markdownBody(items, L, target, o.project)}` }];
    case 'system-prompt': {
      const g = groups(items);
      const out = [MARK, L.intro];
      if (items.some((i) => i.provenance.kind !== 'you-said')) out.push(L.inferredNote);
      for (const [key, label] of [['must', L.must], ['general', L.general], ['procedures', L.procedures], ['habits', L.habits]] as const) {
        if (g[key].length) out.push('', `${label}:`, ...g[key].map((i) => line(i, L, target)));
      }
      return [{ path: 'system-prompt.txt', content: `${out.join('\n')}\n` }];
    }
    case 'cursor': {
      const g = groups(items);
      const files: CompiledFile[] = [];
      const always = [...g.must];
      const rest = [...g.general, ...g.procedures, ...g.habits];
      if (always.length) files.push({ path: '.cursor/rules/forgen-way.mdc', content: `---\ndescription: ${yamlStr(L.title)}\nalwaysApply: true\n---\n${MARK}\n${markdownBody(always, L, target, o.project)}` });
      if (rest.length) files.push({ path: '.cursor/rules/forgen-way-situational.mdc', content: `---\ndescription: ${yamlStr(`${L.title}: ${L.general}, ${L.procedures}`)}\nalwaysApply: false\n---\n${MARK}\n${markdownBody(rest, L, target, o.project)}` });
      return files;
    }
    case 'workflow': {
      const byCat = new Map<string, WayItem[]>();
      for (const i of items) byCat.set(i.category ?? i.kind, [...(byCat.get(i.category ?? i.kind) ?? []), i]);
      const out = [MARK, `# ${L.check}`, ''];
      for (const [cat, list] of [...byCat].sort((a, b) => a[0].localeCompare(b[0]))) {
        out.push(`## ${cat}`, ...list.map((i) => `- [ ] ${oneLine(i.statement)}${whenNote(i, L, target)}${tag(i, L)}`), '');
      }
      return [{ path: 'forgen-way-checklist.md', content: `${out.join('\n')}` }];
    }
    case 'skill': {
      const used = new Set<string>();
      return items.map((i) => skillFile(i, skillName(i, used), L, notes));
    }
    case 'json':
      return [{ path: 'forgen-way.json', content: `${JSON.stringify({ schema: 'forgen-way/1', generator: 'forgen-way', generated_at: genAt, project: o.project ?? null, items }, null, 2)}\n` }];
  }
}

export function compile(way: Way, target: CompileTarget, o: CompileOptions = {}): CompileResult {
  const omitted: Omitted[] = [];
  const degraded: Degraded[] = [];
  const warnings: string[] = [];
  const knownProjects = new Set(way.items.flatMap((i) => i.projects));
  let pool: WayItem[] = [];
  for (const i of way.items) {
    if (o.only && !o.only.includes(i.id)) { omitted.push({ id: i.id, reason: 'not-selected' }); continue; }
    if (i.kind === 'rule' && i.status && i.status !== 'active') { omitted.push({ id: i.id, reason: 'not-selected', detail: i.status }); continue; }
    if (i.projects.length && !(o.project && i.projects.includes(o.project))) { omitted.push({ id: i.id, reason: 'project-scope', detail: i.projects.join(',') }); continue; }
    if (i.kind === 'habit' && !o.habits && !o.only) { omitted.push({ id: i.id, reason: 'habit-excluded' }); continue; }
    if (i.conflicts_with) { omitted.push({ id: i.id, reason: 'conflict', detail: `활성 룰 ${i.conflicts_with.slice(0, 8)} 과 상반` }); continue; }
    if (target === 'skill' && !isSkillable(i) && !o.only) {
      omitted.push({ id: i.id, reason: 'not-a-procedure', detail: i.kind === 'solution' ? '사용 시점(Context) 없음: forgen way draft skill "<주제>"' : '룰은 사용 시점이 없다: forgen way draft skill "<주제>"' });
      continue;
    }
    pool.push(i);
  }

  // 렌더러와 같은 render_key 중복 제거 (같은 키면 순위가 높은 하나만)
  const best = new Map<string, WayItem>();
  for (const i of pool) {
    if (i.kind !== 'rule' || !i.render_key) continue;
    const cur = best.get(i.render_key);
    if (!cur || comparePriority(i, cur) < 0) best.set(i.render_key, i);
  }
  pool = pool.filter((i) => {
    const w = i.kind === 'rule' && i.render_key ? best.get(i.render_key) : undefined;
    if (w && w !== i) { omitted.push({ id: i.id, reason: 'duplicate', detail: `render_key ${i.render_key} → ${w.id.slice(0, 8)}` }); return false; }
    return true;
  });

  // 다른 프로젝트 전용 계기는 숨긴다 (전역 항목의 trigger 가 프로젝트 이름을 말하는 경우)
  const foreign = [...knownProjects].filter((k) => k !== o.project);
  pool = pool.map((i) => (i.applies_when && projectKeysIn(i.applies_when, foreign).length ? { ...i, applies_when: '' } : i));

  // 다른 모델이 읽는 산출물: 호스트 전용 꼬리 절 제거, 남으면 degraded
  const hostNotes: Degraded[] = [];
  if (!CLAUDE_TARGETS.has(target)) {
    pool = pool.map((i) => {
      if (!HOST_TERM.test(i.statement)) return i;
      const r = scrubHostTail(i.statement);
      if (r.removed) hostNotes.push({ id: i.id, reason: '호스트 전용 꼬리 절 제거 (다른 모델 대상)' });
      if (r.residual) hostNotes.push({ id: i.id, reason: '호스트 전용 표현이 문장 안에 남음 (다른 모델에서는 뜻이 안 통할 수 있다)' });
      return r.removed ? { ...i, statement: r.text } : i;
    });
  }

  pool.sort((a, b) => comparePriority(a, b));
  const L = pickLang(pool.length ? pool : way.items);
  const budget = target === 'json' ? undefined : (o.budget ?? DEFAULT_BUDGET[target]);
  const notes: string[] = [];
  const chosen: WayItem[] = [];
  for (const i of pool) {
    if (budget !== undefined) {
      const size = renderFiles(target, [...chosen, i], L, o, []).reduce((n, f) => n + f.content.length, 0);
      if (size > budget) { omitted.push({ id: i.id, reason: 'budget', detail: `${budget}자 예산 초과` }); continue; }
    }
    chosen.push(i);
  }
  const files = chosen.length ? renderFiles(target, chosen, L, o, notes, way.generated_at) : [];
  const chosenIds = new Set(chosen.map((i) => i.id));
  if (target !== 'json') {
    for (const i of chosen) if (i.enforceable) degraded.push({ id: i.id, reason: `자문으로 전환: ${target} 산출물은 룰을 강제하지 못한다` });
    degraded.push(...hostNotes.filter((h) => chosenIds.has(h.id)));
  }
  for (const n of notes) degraded.push({ id: n.split(':')[0], reason: n.slice(n.indexOf(':') + 2) });

  if (!o.project) {
    const suspects = projectSpecificSuspects(chosen);
    const globalRules = chosen.filter((i) => i.kind === 'rule' && !i.projects.length).length;
    if (globalRules > 0) {
      warnings.push(`프로젝트 미지정 전역 산출물: 룰 ${globalRules}개 중 ${suspects.length}개가 프로젝트 전용일 수 있음. 분류: forgen rule classify-projects --project <키> --keywords a,b (또는 forgen rule set-project <id> <키>)`);
      if (target !== 'json') for (const s of suspects) degraded.push({ id: s.id, reason: `프로젝트 전용일 수 있음: ${s.why}` });
    }
  }
  return { files, omitted, degraded, warnings };
}
