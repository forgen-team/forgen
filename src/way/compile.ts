/** Claude 쪽 산출물(호스트 용어가 그대로 통한다). 나머지는 다른 모델이 읽는다. */
const CLAUDE_TARGETS: ReadonlySet<CompileTarget> = new Set(['claude-rules', 'skill', 'json']);
/** 룰의 `trigger`(교정이 필요했던 계기)를 싣는 대상: 교정 맥락을 같이 보여 주는 쪽만. 그 밖에서는 잡음이다. */
const TRIGGER_TARGETS: ReadonlySet<CompileTarget> = new Set(['claude-rules', 'skill', 'json']);

const HOST_TERM = /secret-filter|db-guard|slop-detector|\bhooks?\b|훅|\bmcp\b|claude\s*code|claude\s*(?:가|는|를|의|도|에게|한테)?(?![a-z])|클로드|\bforgen\b|\.claude\b/i;
const CLAUSE_SEP = /(?<=[.!?。])\s+|\s+[—–]\s+|;\s+|\s+\/\/\s+/;

/** 문장 끝에 붙은 호스트 전용 절(문장·대시·세미콜론·괄호 단위)만 떼어 낸다. 앞부분은 한 글자도 바꾸지 않는다. 남는 호스트 용어는 residual. */
export function scrubHostTail(statement: string): { text: string; removed: boolean; residual: boolean } {
  let text = statement.trimEnd();
  let removed = false;
  for (let guard = 0; guard < 4; guard++) {
    // 끝 괄호절
    const paren = /\s*[(（][^()（）]*[)）]\s*[.。]?$/.exec(text);
    if (paren && HOST_TERM.test(paren[0]) && text.slice(0, paren.index).trim().length >= 12) { text = text.slice(0, paren.index).trimEnd(); removed = true; continue; }
    // 끝 절
    const seps = [...text.matchAll(new RegExp(CLAUSE_SEP.source, 'g'))];
    const last = seps.at(-1);
    if (!last || last.index === undefined) break;
    const tail = text.slice(last.index + last[0].length);
    const head = text.slice(0, last.index).replace(/[\s;—–]+$/, '');
    if (HOST_TERM.test(tail) && head.length >= 12) { text = head; removed = true; continue; }
    break;
  }
  return { text, removed, residual: HOST_TERM.test(text) };
}

const PRODUCT_NOT = new Set(['Always', 'Never', 'Prefer', 'Avoid', 'Keep', 'Before', 'After', 'When', 'Make', 'Write', 'Check', 'Ensure', 'Only', 'Every', 'Each', 'Please', 'Don', 'Run', 'Read', 'Test', 'Tests', 'Commit', 'Ask']);
const PRODUCT_RE = /^(?:\[[^\]]*\]\s*)?([A-Z][A-Za-z0-9_]{3,})(?=[\s(,:은는이가의]|$)/;

function projectKeysIn(text: string, keys: Iterable<string>): string[] {
  const lower = text.toLowerCase();
  return [...keys].filter((k) => k.length >= 3 && lower.includes(k));
}

/** 프로젝트가 지정되지 않은 전역 항목 중 프로젝트 전용일 수 있는 것: 알려진 프로젝트 키가 문장에 나오거나, 문장이 제품 이름으로 시작한다. */
export function projectSpecificSuspects(items: WayItem[]): Array<{ id: string; why: string }> {
  const keys = new Set(items.flatMap((i) => i.projects));
  const out: Array<{ id: string; why: string }> = [];
  for (const i of items) {
    if (i.kind !== 'rule' || i.projects.length) continue;
    const hit = projectKeysIn(`${i.statement} ${i.applies_when}`, keys)[0];
    if (hit) { out.push({ id: i.id, why: `프로젝트 "${hit}" 언급` }); continue; }
    const m = PRODUCT_RE.exec(i.statement.trim());
    if (m && !PRODUCT_NOT.has(m[1])) out.push({ id: i.id, why: `"${m[1]}" 로 시작(제품·프로젝트 이름일 수 있음)` });
  }
  return out;
}

/** 사람이 읽을 상황 문구인가. 공백 없는 식별자(`secret-leak`)나 프로필 표지는 아니다. */
function readableWhen(i: WayItem): string {
  const w = oneLine(i.applies_when);
  if (!w || w === 'profile' || i.statement.includes(w) || (!/\s/.test(w) && /^[\w.:-]+$/.test(w))) return '';
  return w;
}

function whenNote(i: WayItem, L: Strings, target: CompileTarget): string {
  if (i.kind === 'rule' && !TRIGGER_TARGETS.has(target)) return '';
  const w = readableWhen(i);
  return w ? ` (${i.kind === 'rule' ? L.trig : L.when}: ${w})` : '';
}

function line(i: WayItem, L: Strings, target: CompileTarget): string {
  const when = whenNote(i, L, target);
  const body = i.statement.trim().replace(/\n/g, '\n  ');
  return `- ${body}${when}${tag(i, L)}`;
}

function groups(items: WayItem[]) {
  return {
    must: items.filter((i) => i.kind === 'rule' && (i.strength === 'hard' || i.strength === 'strong')),
    general: items.filter((i) => i.kind === 'rule' && (i.strength === 'default' || i.strength === 'soft')),
    procedures: items.filter((i) => i.kind === 'solution'),
    habits: items.filter((i) => i.kind === 'habit'),
  };
}

function markdownBody(items: WayItem[], L: Strings, target: CompileTarget, project?: string): string {
  const g = groups(items);
  const out: string[] = [`# ${L.title}`, ''];
  if (project) out.push(`${L.project}: ${project}`, '');
  out.push(L.intro);
  if (items.some((i) => i.provenance.kind !== 'you-said')) out.push(L.inferredNote);
  for (const [key, label] of [['must', L.must], ['general', L.general], ['procedures', L.procedures], ['habits', L.habits]] as const) {
    if (!g[key].length) continue;
    out.push('', `## ${label}`, ...g[key].map((i) => line(i, L, target)));
  }
  return `${out.join('\n')}\n`;
}

