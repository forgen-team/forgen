/**
 * 한국어 회화체 잔여물 처리 — extractTags 의 한국어 분기 전처리.
 *
 * 문제: "이거 같아 왜냐면 시켜보자" 같은 회화체 프롬프트에서 extractTags 가 8칸을 어미/지시어/접속어로
 * 채워 실제 주제어가 밀려난다(ADR-017 §1.5a 실측). KO_STOPWORDS 는 문서체 명사 위주라 이를 못 거른다.
 *
 * 처리 (결과는 `string | null`):
 *   - 순수 구어(지시어·접속어·종결 어미·"같아" 류)        → null (드롭)
 *   - 명사+구어 어미 ("검증해줘", "가능한", "배포하는지") → 어간만 남김 ("검증", "가능", "배포")
 *   - 그 외                                               → 원문 그대로
 * 어간이 2자 미만이면 어미 제거를 하지 않는다("이해"→"이" 방지).
 */

/** 순수 구어 — 단독으로 나오면 태그로 가치가 없다. */
const COLLOQUIAL_DROP = new Set<string>([
  // 종결·연결 어미 단독
  '같아', '같은데', '같네', '같다', '같애', '같아서', '같은', '거야', '거예요', '건데', '인데', '는데', '은데',
  '하는데', '했는데', '한데', '해줘', '해봐', '해라', '해요', '하자', '보자', '볼까', '할까', '할래', '줄래',
  '시켜보자', '시켜봐', '시켜줘', '시켜', '알려줘', '말해줘', '맞아', '맞지', '아니야', '아니고', '아닌데',
  '했는지', '하는지', '인지', '할지', '해야', '해야할', '해야하는', '위한', '대한', '통한', '관한', '진행해', '진행해줘',
  // 접속·지시·대명사
  '왜냐면', '왜냐하면', '그래서', '그러면', '그럼', '그런데', '근데', '그리고', '하지만', '그러나', '그래도',
  '이거', '저거', '그거', '이게', '그게', '저게', '이건', '그건', '이걸', '그걸', '여기', '거기', '저기',
  '지금', '이제', '우리', '어떤', '어떻게', '어디', '뭔가', '뭐든', '전부', '일단', '아무', '그냥', '좀더',
  '혹시', '아직', '다시', '계속', '바로', '먼저', '나중', '그다음',
]);

/**
 * 어간 + 구어 어미. 긴 어미가 먼저 매칭되도록 정렬한다.
 * 어간 그룹은 한글 2자 이상(lazy) — 1자 어간("이해"→"이")은 거부.
 */
const COLLOQUIAL_ENDINGS = [
  '해주세요', '해줄래', '해줘', '해봐', '해보자', '시켜보자', '시켜줘', '시켜봐',
  '하는지', '했는지', '할지', '하는데', '했는데', '한데', '인데', '는데', '은데',
  '하자', '해야', '해도', '하면', '해서', '했던', '하는', '할', '한', '해',
].sort((a, b) => b.length - a.length);

const COLLOQUIAL_ENDING_RE = new RegExp(`^([가-힣]{2,}?)(${COLLOQUIAL_ENDINGS.join('|')})$`);

export function normalizeColloquialKo(word: string): string | null {
  if (COLLOQUIAL_DROP.has(word)) return null;
  const m = word.match(COLLOQUIAL_ENDING_RE);
  if (!m) return word;
  const stem = m[1];
  return COLLOQUIAL_DROP.has(stem) ? null : stem;
}
